#!/usr/bin/env node
/**
 * **数字必须带口径（`TASK-263`）—— 只做可机械检查的那一半。**
 *
 * 立卡背景（同一天三次误判，根因同一个）：
 *   ① 「`任何×没有` 评审记 **12** 行 / 实现 `grep` 得 **1** 行」── 两个都对：12 = 不设上限档、1 = `gap≤4` 档；
 *   ② 「**15** 条无 `reason` 畸形」── 现算 **0** 条（很可能把引用形态 `sameAsSeq` 当成了畸形）；
 *   ③ `REV-115` 核 `dispatch/aborted`：`grep -c` = **12 行**（别的事件正文提到这词）、按 `event.type` = **0**。
 * 三次都不是"谁数错了"，而是**同一句话里的数字没写口径**：**数字离了口径就不是读数，只是字符。**
 *
 * ## 本脚本扫什么（以及刻意不扫什么）
 *
 * **只扫评审核实记录**：`.sdo/reviews/verified.yml` 里每条 `evidence`（即 `verify-review` 的 `proof` 载体）
 * 的文本。**不扫全文** —— 全仓每处数字都要口径的 linter 会把守卫自己淹死（卡面、注释、变更日志里到处是
 * 编号与哈希），而"核实结论里的数字"恰好是**唯一**必须当场可复算的那一面。
 *
 * 载体不存在（未初始化的仓 / 插件包被单独 checkout）时：打印一行 `carrier: absent` 并 **exit 0**
 * —— 项目数据不在交付物里，这条检查不该因为"你没有台账"而红。
 *
 * ## 什么算「读数」（`READING_SHAPES`）
 *
 * 一个数字只有**声称自己是计数**时才算读数，四种形态任一命中即算：
 *   · `量词`      —— 紧跟中文量词（`12 行` / `15 条` / `3 次` / `7 个` / `50%`）；
 *   · `英文计数词` —— 紧跟 `tests` / `pass` / `fail` / `lines` / `files` / `entries` …（`15 tests`、`2 fail`）；
 *   · `加粗`      —— 被 `**` 包住（`**0**`：断言里的强调读数）；
 *   · `结果位`    —— 紧跟在 `=` / `→` / `->` 后面（`按 event.type 精确计数 = 0`）。
 *
 * **明确不算读数**（不是"漏判"，是判据的一部分 —— 它们是**名字 / 位置 / 版本**，不是计数）：
 *   `REV-001`、`TASK-263`、`CT-024`、`TR-008`、`m249`、`seq 847` 这类标识符与编号；
 *   `721d98…` 这类哈希 / 十六进制串；`2026-10-13` 这类 ISO 日期；`0.1.6` 这类版本号；
 *   `src/a.ts:254`、`:427-434` 这类路径与行号锚点。
 *   机械口径 = 数字 token 的**紧邻字符**是字母/数字/`.`/`#`/`/`/`:`/`\`/`-` 时不算独立数字
 *   （见 `NUMBER` 的前后视断言）。这条边界比"凡是数字都要口径"窄，**窄是故意的**：宁可漏掉
 *   `hits: 5` 这种边角（登记在案），也不要用噪音把守卫逼成"没人看"。
 *
 * ## 什么算「带口径」（`FACETS`，五面）
 *
 * 数字**所在的片段**（以 `。` `；` `;` 换行切分）里必须出现 **`口径:` 标记**（半角/全角冒号都认，
 * 且不许是 `旧口径：` / `新口径：` 这种把标记当前缀的普通散文）。标记之后的内容按五面机检：
 *
 *   | 面 | 要写清什么 |
 *   |---|---|
 *   | 正则 | 用什么模式匹配（正则 / 字面串 / 具体命令） |
 *   | 路径 | 匹配面是哪个目录或文件 |
 *   | 窗口 | 全行匹配还是同行匹配、有没有上限 |
 *   | 计数 | 数行还是数次数（`wc -l` / `grep -c`） |
 *   | 类型轴 | 按 `event.type` 精确计数，还是按正文匹配 |
 *
 * **缺项可容忍**（写全四面当然更好，本脚本不因"少写一面"判红）；**一面都没有就不算读数**
 * —— `口径:` 后面跟一句空话（`口径: 很准`）仍然是缺标记，仍然红。这条就是卡面那句
 * 「缺哪项可容忍，一项都没有就不能算读数」的机械形态。
 *
 * ## 存量登记（`KNOWN_UNMARKED`）与它为什么不乱杀
 *
 * 判据立起来那一刻，盘上已有几百条核实记录**一行口径都没有**。把它们当场全判红 = 让守卫的第一天
 * 就是红的 = 它们会被"临时跳过"，守卫随即死掉。所以：**存量按身份登记**，每条给 `n`（该记录名下的
 * 未带口径读数**处数**）与非空 `why`；判据**不为登记放宽**：
 *
 *   · 登记之外**截止时刻之内**的记录出现未带口径读数 ⇒ **红并点名**（不许靠"少登记几条"隐瞒）；
 *   · 登记的 `n` 与现算不等（多了少了、记录没了）⇒ **红并要求收紧登记** —— 这是"登记表不是永久豁免"的
 *     那一半：谁补了口径，就来把这条删掉或改小；
 *   · 登记**不改写任何历史 proof 文本**（历史是事实，`TASK-263` 的 DoD 明写"要登记不要改写"）。
 *
 * **截止时刻（`REGISTRY_AS_OF`）是干什么的**：台账是**只增**且**并发在写**的（别的会话随时在
 * `verify-review`）。若"任何未登记读数都判红"直接进全量，本卡落地后**下一分钟**就有别人的核实记录把
 * 全量顶红 —— 那不是守卫，那是噪音源。所以把面切成两半：
 *
 *   · **截止时刻之内**（`at <= REGISTRY_AS_OF`）⇒ 属于**存量**：必须逐条登记（CI 判据）；
 *   · **截止时刻之后** ⇒ 属于**新记录**：本脚本照旧**exit 1 并点名**（"新记录必须写口径"这一半在这里），
 *     但 CI 只打印读数、不判红（否则全量会跟着别人的正常核实一起红）。
 *   登记表由 `--write-registry` 机械重生成（把截止时刻推到当前最新一条），`--emit-registry` 只打印不写盘。
 *   **重生成会让"新记录"变成"存量"**，所以两个命令都会打印差集（`+ 新增 / - 减少 / ~ 变化`）——
 *   静默重生成就是"把守卫关掉"，明细可见才不是（与 `refresh-prose-gap.mjs` 同一纪律）。
 *
 * ## 用法
 *
 *   node scripts/check-number-provenance.mjs                     只检查（不同步 ⇒ exit 1；载体缺失 ⇒ exit 0）
 *   node scripts/check-number-provenance.mjs --carrier=<path>    换载体（相对路径按**仓库根**解析）
 *   node scripts/check-number-provenance.mjs --emit-registry     打印现算登记表（不写盘）
 *   node scripts/check-number-provenance.mjs --write-registry    把现算登记表写回本文件（带写前自证）
 *   node scripts/check-number-provenance.mjs --json              机读输出（字段名全 ASCII，给守卫用）
 *   node scripts/check-number-provenance.mjs --help              打印定义表
 *
 * 退出码：`0` 同步 / 无可判项；`1` 有未登记的读数（含截止之后的新记录）、或登记已过期。
 */
