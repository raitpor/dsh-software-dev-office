function main(argv) {
  const args = argv.slice(2)
  if (args.includes('--help') || args.includes('-h')) {
    console.log(helpText())
    return 0
  }
  const carrierArg = args.find((arg) => arg.startsWith('--carrier='))
  const carrier = carrierArg === undefined ? CARRIER : carrierArg.slice('--carrier='.length)
  const result = check({ carrier })
  if (args.includes('--emit-registry') || args.includes('--write-registry')) {
    if (result.records.length === 0) {
      console.error('✗ 载体内没有记录可登记（carrier absent 或空台账）')
      return 1
    }
    if (result.scope !== 'project' && args.includes('--write-registry')) {
      console.error('✗ 只接受本仓载体写登记表（--carrier 换过的载体不写盘：夹具不许覆盖真登记表）')
      return 1
    }
    const { entries, asOf } = registryFrom(result.scan.perRecord, result.records, result.scan.newest)
    const delta = result.scope === 'project' ? registryDelta(KNOWN_UNMARKED, entries) : { added: [], changed: [], removed: [] }
    console.log(`现算：${result.scan.records} 条记录 / ${result.scan.unmarked.length} 处未带口径；登记 ${entries.length} 条（截止 ${asOf}）`)
    if (delta.added.length > 0) console.log(`  + 新增 ${delta.added.length} 条：${delta.added.slice(0, 20).join(', ')}${delta.added.length > 20 ? ' …' : ''}`)
    if (delta.changed.length > 0) console.log(`  ~ 变化 ${delta.changed.length} 条：${delta.changed.slice(0, 20).join(', ')}${delta.changed.length > 20 ? ' …' : ''}`)
    if (delta.removed.length > 0) console.log(`  - 减少 ${delta.removed.length} 条（有人补了口径 ⇒ 收紧）：${delta.removed.slice(0, 20).join(', ')}${delta.removed.length > 20 ? ' …' : ''}`)
    if (args.includes('--emit-registry')) {
      console.log(renderRegistry(entries, asOf))
      return 0
    }
    const written = writeRegistry(entries, asOf)
    console.log(`✓ 已重写存量登记：${written.written} 条 / asOf ${written.asOf}`)
    return 0
  }
  if (args.includes('--json')) {
    console.log(JSON.stringify(toJson(result), null, 2))
    return result.audit.unregistered.length === 0 && result.audit.stale.length === 0 ? 0 : 1
  }
  console.log(formatReport(result))
  return result.audit.unregistered.length === 0 && result.audit.stale.length === 0 ? 0 : 1
}

