/* ————————————————————————————————————————————————————————————————————————————————
 * 一、口径标记的**五个面**（判据写死在这里；文档与守卫都只读这张表）
 * ———————————————————————————————————————————————————————————————————————————————— */

/**
 * 五面检测器。`test` 吃的是**标记之后**的那段文本（含标记本身，因此 `grep -c` 这类既能算"正则"也能算
 * "计数"的写法会同时命中两面 —— 这是有意的宽容，判据只在"一面都没有"时红）。
 */
export const FACETS = [
  {
    key: '正则',
    asks: '用什么模式匹配（正则 / 字面串 / 具体命令）',
    test: /正则|regex|regexp|pattern|grep|--include|=~/iu,
  },
  {
    key: '路径',
    asks: '匹配面是哪个目录或文件（"全仓"就等于没说）',
    test: /(?:src|test|docs|scripts|lib|skills|presets|node_modules|\.sdo)\/|\S+\.(?:ts|tsx|js|mjs|cjs|yml|yaml|json|jsonl|md|txt)\b|目录|文件面|全仓/iu,
  },
  {
    key: '窗口',
    asks: '全行匹配还是同行匹配、有没有上限（`gap≤4` / 不设上限）',
    test: /窗口|全行|同行|行内|不限|不设上限|上限|±\s*\d|gap\s*[≤<>=]/iu,
  },
  {
    key: '计数',
    asks: '数行还是数次数（`wc -l` / `grep -c` / 数条）',
    test: /数行|行数|次数|条数|计数|wc\s+-l|grep\s+-c|\s-c\b/iu,
  },
  {
    key: '类型轴',
    asks: '按 `event.type` 精确计数，还是按正文匹配',
    test: /event\.type|按类型|类型字段|正文|event\b/iu,
  },
]

/**
 * `口径:` 标记本体。半角/全角冒号都认；**前面不许紧贴汉字或字母数字** ——
 * `旧口径：` / `新口径：` / `统一口径：` 是普通散文（"当时的说法"），不是给数字标口径的标记。
 */
export const MARKER = /(?<![\u4e00-\u9fffA-Za-z0-9_])口径\s*[:：]/u

/**
 * 数字 token 的边界：紧邻字母/数字/`.`/`#`/`/`/`:`/`\`/`-` 时**不是独立数字**（⇒ 不算读数候选）。
 * 这一条同时排掉了标识符（`REV-001`）、哈希（`721d98…`）、ISO 日期（`2026-10-13`）、版本号（`0.1.6`）
 * 与路径行号（`src/a.ts:254`、`:427-434`）。
 */
const NUMBER = /(?<![\w.#/:\\-])\d+(?:\.\d+)?(?![\w./:\\-])/gu

/** 中文量词（`12 行` / `15 条` / `7 个` / `50%`）。 */
const CN_COUNT = /^(?:条|行|次|个|处|项|份|格|篇|层|名|位|字|点|家|人|倍|站|台|段|块|句|%|％)/u

/** 英文计数词（`15 tests` / `13 pass` / `2 fail` / `3 files`）。 */
const EN_COUNT = /^(?:tests?|pass|fail|lines?|files?|entries|hits|cases?|sites?|records?|rows?|nodes?|pages?|items?)\b/iu

/** 结果位（数字紧跟在 `=` / `→` / `->` 之后，允许中间是 `**`）。 */
const RESULT_BEFORE = /(?:=|＝|→|->)\s*\*{0,2}$/u

/** 读数形态名（与文件头那张说明同源；改这里就等于改判据说明）。 */
export const READING_SHAPES = ['量词', '英文计数词', '加粗', '结果位']

/** 片段分隔符：一句一个片段（`。` `；` `;` 换行）。 */
const SEGMENT_BREAKS = new Set(['。', '；', ';', '\n'])

/**
 * 这个数字**声称自己是读数**吗？返回命中的形态名（空数组 ⇒ 不是读数候选，直接放过）。
 * 判据只看紧邻字符与包裹标记，不读任何措辞（因此中英同判，也不需要词表）。
 */
export function readingShapesAt(text, index, token) {
  const after = text.slice(index + token.length)
  const lead = /^[ \t]*/u.exec(after)[0]
  const head = after.slice(lead.length)
  const shapes = []
  if (CN_COUNT.test(head)) shapes.push('量词')
  if (EN_COUNT.test(head)) shapes.push('英文计数词')
  if (text.slice(Math.max(0, index - 2), index) === '**' && text.slice(index + token.length, index + token.length + 2) === '**') {
    shapes.push('加粗')
  }
  if (RESULT_BEFORE.test(text.slice(Math.max(0, index - 12), index))) shapes.push('结果位')
  return shapes
}

/** 一段核实文本里的**读数候选**（带 index，供片段定位）。 */
export function readingsOf(evidence) {
  const out = []
  for (const match of String(evidence ?? '').matchAll(NUMBER)) {
    const token = match[0]
    const index = match.index ?? 0
    const shapes = readingShapesAt(evidence, index, token)
    if (shapes.length === 0) continue
    out.push({ token, index, shapes })
  }
  return out
}

/** 数字所在的片段（`[start, end)`，不含分隔符本身）。 */
export function segmentAt(text, index) {
  let start = 0
  for (let i = 0; i < index; i += 1) if (SEGMENT_BREAKS.has(text[i])) start = i + 1
  let end = text.length
  for (let i = index; i < text.length; i += 1) {
    if (SEGMENT_BREAKS.has(text[i])) { end = i; break }
  }
  return { start, end, text: text.slice(start, end) }
}

/**
 * 片段里的口径标记解析结果：
 *   · `undefined` —— 没有标记（缺标记 ⇒ 红）；
 *   · `[]`        —— 有标记但**一面都没有**（空标记 ⇒ 仍算缺标记，红）；
 *   · `['正则', …]` —— 认得出的面（缺项可容忍，绿）。
 */
export function markerFacets(segmentText) {
  const hit = MARKER.exec(segmentText)
  if (hit === null) return undefined
  const payload = segmentText.slice(hit.index)
  return FACETS.filter((facet) => facet.test.test(payload)).map((facet) => facet.key)
}

/** 判定一处读数：带没带有效口径。 */
export function judgeReading(evidence, reading) {
  const segment = segmentAt(evidence, reading.index)
  const facets = markerFacets(segment.text)
  if (facets === undefined) return { covered: false, reason: 'missing-marker', segment: segment.text.trim() }
  if (facets.length === 0) return { covered: false, reason: 'empty-marker', segment: segment.text.trim() }
  return { covered: true, reason: 'ok', facets, segment: segment.text.trim() }
}

/* ————————————————————————————————————————————————————————————————————————————————
 * 二、载体解析：`.sdo/reviews/verified.yml` 的子集（只认本脚本用到的四个键）
 * ———————————————————————————————————————————————————————————————————————————————— */

/**
 * 把载体文本切成核实记录 `{ id, reviewId, index, at, evidence }`。
 *
 * 只认 YAML 子集（缩进 2 的列表项 + 缩进 4 的键）：`evidence` 在本仓是**单行**标量，因此续行
 * （缩进 ≥6，如 `revisedFrom:` 的子键）一律**不并入** evidence —— 不是完整 YAML 解析器，也不需要是。
 */
export function parseVerifications(text) {
  const records = []
  let current
  for (const line of String(text ?? '').split('\n')) {
    const head = /^ {2}- reviewId:\s*(\S+)\s*$/u.exec(line)
    if (head !== null) {
      current = { reviewId: head[1], index: 0, at: '', evidence: '' }
      records.push(current)
      continue
    }
    if (current === undefined) continue
    const index = /^ {4}index:\s*(\d+)\s*$/u.exec(line)
    if (index !== null) { current.index = Number(index[1]); continue }
    const at = /^ {4}at:\s*(\S+)\s*$/u.exec(line)
    if (at !== null) { current.at = at[1]; continue }
    const evidence = /^ {4}evidence:\s?(.*)$/u.exec(line)
    if (evidence !== null) { current.evidence = evidence[1]; continue }
  }
  return records.map((record) => ({ ...record, id: `${record.reviewId}#${record.index}` }))
}

/**
 * 扫一批记录：每处读数带上 `id` / `at` 与判定；`unmarked` 只留**未带有效口径**的那些。
 * 纯函数（不读盘）—— 守卫夹具与现盘走同一条路，读数才可比。
 */
export function scanRecords(records) {
  const readings = []
  const unmarked = []
  for (const record of records) {
    for (const reading of readingsOf(record.evidence)) {
      const verdict = judgeReading(record.evidence, reading)
      const row = { id: record.id, at: record.at, token: reading.token, shapes: reading.shapes, ...verdict }
      readings.push(row)
      if (!verdict.covered) unmarked.push(row)
    }
  }
  const perRecord = new Map()
  for (const row of unmarked) perRecord.set(row.id, (perRecord.get(row.id) ?? 0) + 1)
  const newest = records.reduce((max, record) => (record.at > max ? record.at : max), '')
  return { records: records.length, readings, unmarked, perRecord, newest }
}

