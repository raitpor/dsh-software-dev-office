/**
 * 从脚本源文本里读回登记表体（只认两行之间那两种注释行，**不执行**文件里任何东西）：
 *   · `// asOf: <ISO>`                          —— 截止时刻；
 *   · `// <id> n=<处数> why=<非空说明>`          —— 一条存量登记。
 */
export function readRegistry(source) {
  const begin = source.indexOf(REGISTRY_BEGIN)
  const end = source.indexOf(REGISTRY_END)
  if (begin === -1 || end === -1 || end < begin) throw new Error('本文件缺 known-unmarked 哨兵（--write-registry 只认这两行之间的表体）')
  const body = source.slice(begin + REGISTRY_BEGIN.length, end)
  const asOf = /\/\/ asOf:\s*(\S+)/u.exec(body)
  const entries = []
  for (const line of body.split('\n')) {
    const hit = /^\s*\/\/ (\S+) n=(\d+) why=(.+)$/u.exec(line)
    if (hit === null) continue
    entries.push({ id: hit[1], n: Number(hit[2]), why: hit[3] })
  }
  return { asOf: asOf === null ? '' : asOf[1], entries }
}

/** 登记表体的**渲染**（确定性输出：`asOf` 一行 + 按 id 排序的逐条登记；生成物可逐字节比对）。 */
export function renderRegistry(entries, asOf) {
  const lines = [`// asOf: ${asOf}`]
  let total = 0
  for (const entry of entries) total += entry.n
  lines.push(`// 存量登记 ${entries.length} 条 / 合计 ${total} 处（由 --write-registry 机械生成）`)
  lines.push('// why 的口径：这些核实记录在判据立起来之前入库，读数未带「口径:」标记 —— 历史是事实，登记不改写；')
  lines.push('// 收紧路径：该记录被再次核实时补口径，然后 `--write-registry` 会把这条删掉 / 改小（差集打印 `- 减少`）。')
  for (const entry of entries) {
    if (entry.id.trim() === '' || entry.why.trim() === '' || !Number.isInteger(entry.n) || entry.n <= 0) {
      throw new Error(`登记条目残缺（id/why 不许空、n 必须是正整数）：${JSON.stringify(entry)}`)
    }
    lines.push(`// ${entry.id} n=${entry.n} why=${entry.why.replace(/\s+/gu, ' ')}`)
  }
  return lines.join('\n')
}

/** `id` 的排序键：`REV-001#2` < `REV-001#10` < `REV-002#0`（按 review 号再按 index，不按字符串）。 */
function idOrder(a, b) {
  const split = (id) => {
    const [review, index] = id.split('#')
    const num = Number((review ?? '').replace(/\D+/gu, ''))
    return [Number.isNaN(num) ? 0 : num, Number(index ?? 0)]
  }
  const [ra, ia] = split(a)
  const [rb, ib] = split(b)
  if (ra !== rb) return ra - rb
  return ia - ib
}

/** 现算出的存量表（`why` 里带**入库日期** + 处数，逐条可核）+ 截止时刻 = 现盘最新一条的 `at`。 */
export function registryFrom(perRecord, records, asOf) {
  const atOf = new Map(records.map((record) => [record.id, record.at.slice(0, 10)]))
  const entries = [...perRecord.entries()]
    .map(([id, n]) => ({
      id,
      n,
      why: `存量（${atOf.get(id) === undefined || atOf.get(id) === '' ? '入库日期未记' : atOf.get(id)} 入库）：${n} 处读数未带「口径:」标记`,
    }))
    .sort((a, b) => idOrder(a.id, b.id))
  return { asOf, entries }
}

/** 本地读回的登记表（本文件自己读自己：一个真源，不另存一份）。 */
const REGISTRY = readRegistry(readFileSync(SELF, 'utf8'))

/** 截止时刻：`at <= 它` 的记录属于存量（必须逐条登记）；之后的属于新记录（脚本判红、CI 只读数）。 */
export const REGISTRY_AS_OF = REGISTRY.asOf

/** 存量登记表：`{ id, n, why }`（`id` = `<reviewId>#<index>`；`n` = 该记录名下未带口径的**处数**）。 */
export const KNOWN_UNMARKED = REGISTRY.entries

/**
 * **对账**（纯函数，返回结构化事实；打印与退出码由 `formatReport` / `main` 决定）：
 *   · `withinCutoff` —— 截止之内、却不在登记里的未带口径读数 ⇒ **隐瞒/漏登记**（CI 判红）；
 *   · `afterCutoff`  —— 截止之后的新记录 ⇒ **新记录没写口径**（脚本判红、CI 只打印）；
 *   · `stale`        —— 登记与现算不等 ⇒ **登记过期，要求收紧**（CI 判红）。
 */
export function audit(scan, registry, asOf) {
  const registered = new Map(registry.map((entry) => [entry.id, entry]))
  const unregistered = scan.unmarked.filter((row) => !registered.has(row.id))
  const withinCutoff = asOf === '' ? [] : unregistered.filter((row) => row.at !== '' && row.at <= asOf)
  const afterCutoff = asOf === '' ? unregistered : unregistered.filter((row) => row.at === '' || row.at > asOf)
  const stale = registry
    .map((entry) => ({ ...entry, actual: scan.perRecord.get(entry.id) ?? 0 }))
    .filter((entry) => entry.actual !== entry.n)
  return {
    unregistered,
    withinCutoff,
    afterCutoff,
    stale,
    registrySize: registry.length,
    registryReadings: registry.reduce((sum, entry) => sum + entry.n, 0),
    asOf,
  }
}

/* ————————————————————————————————————————————————————————————————————————————————
 * 四、入口：读载体 → 扫 → 对账 → 打印/退出码
 * ———————————————————————————————————————————————————————————————————————————————— */

/** 载体的绝对路径（相对路径按仓库根解析）。 */
export function carrierPath(path) {
  return isAbsolute(path) ? path : resolve(ROOT, path)
}

/**
 * 这个载体是不是**本仓的那份台账**？—— 存量登记只对它成立。
 * 换成 `--carrier=<夹具>` 时判据**从零开始**（没有存量豁免、没有截止时刻）：否则拿夹具跑一次就会把
 * 几百条登记全判成"过期"，探针会把守卫自己顶红。
 */
export function isProjectCarrier(path) {
  return carrierPath(path) === carrierPath(CARRIER)
}

/** 读载体文本；载体不存在 ⇒ `undefined`（不是错误）。 */
export function readCarrier(path) {
  const full = carrierPath(path)
  if (!existsSync(full)) return undefined
  return { path: full, text: readFileSync(full, 'utf8') }
}

/** 人类可读的一份读数（每条都点名 + 给片段，避免"只给一个数字"）。 */
export function formatReport(result) {
  const lines = []
  lines.push(`carrier: ${result.carrier ?? '(absent)'} / scope: ${result.scope === 'project' ? '本仓载体（存量登记生效）' : '探针载体（零登记，判据从零开始）'}`)
  if (result.carrier === undefined) {
    lines.push('carrier: absent —— 没有评审核实记录可查（未初始化的仓 / 单独 checkout），本检查不判红')
    return lines.join('\n')
  }
  lines.push(`records: ${result.scan.records} / readings: ${result.scan.readings.length} / unmarked: ${result.scan.unmarked.length}`)
  lines.push(`registry: ${result.audit.registrySize} 条（合计 ${result.audit.registryReadings} 处）/ asOf: ${result.audit.asOf === '' ? '(空)' : result.audit.asOf}`)
  if (result.audit.withinCutoff.length > 0) {
    lines.push(`✗ 存量里没登记的未带口径读数 ${result.audit.withinCutoff.length} 处（截止 ${result.audit.asOf} 之内，不许漏登记）：`)
    for (const row of result.audit.withinCutoff.slice(0, 50)) {
      lines.push(`  - ${row.id} 「${row.token}」 ${row.reason === 'empty-marker' ? '（口径标记里一面都没有）' : '（缺口径标记）'} 片段：${row.segment.slice(0, 160)}`)
    }
    if (result.audit.withinCutoff.length > 50) lines.push(`  … 另有 ${result.audit.withinCutoff.length - 50} 处未显示`)
  }
  if (result.audit.afterCutoff.length > 0) {
    const where = result.scope === 'project'
      ? '✗ 截止之后的新记录里未带口径的读数'
      : '✗ 未带口径的读数（探针载体：判据从零开始，没有存量豁免）'
    lines.push(`${where} ${result.audit.afterCutoff.length} 处（新记录必须写口径；确属存量就 --write-registry 重新基准）：`)
    for (const row of result.audit.afterCutoff.slice(0, 50)) {
      lines.push(`  - ${row.id} 「${row.token}」 ${row.reason === 'empty-marker' ? '（口径标记里一面都没有）' : '（缺口径标记）'} 片段：${row.segment.slice(0, 160)}`)
    }
    if (result.audit.afterCutoff.length > 50) lines.push(`  … 另有 ${result.audit.afterCutoff.length - 50} 处未显示`)
  }
  if (result.audit.stale.length > 0) {
    lines.push(`✗ 登记与现算不等 ${result.audit.stale.length} 条（收紧登记：补了口径就删/改小）`)
    for (const entry of result.audit.stale.slice(0, 50)) lines.push(`  - ${entry.id}：登记 ${entry.n} → 现算 ${entry.actual}`)
  }
  if (result.audit.unregistered.length === 0 && result.audit.stale.length === 0) {
    lines.push(result.scope === 'project' ? '✓ 没有未登记的读数，登记与现算恰好相等' : '✓ 没有未带口径的读数')
  }
  return lines.join('\n')
}

/** 机读形态（字段名全 ASCII：守卫与 CI 读它，不解析中文散文）。 */
export function toJson(result) {
  const brief = (row) => ({ id: row.id, at: row.at, token: row.token, shapes: row.shapes, reason: row.reason })
  return {
    carrier: result.carrier ?? null,
    scope: result.scope,
    asOf: result.audit.asOf,
    records: result.scan.records,
    readings: result.scan.readings.length,
    unmarked: result.scan.unmarked.length,
    unregistered: result.audit.unregistered.map(brief),
    withinCutoff: result.audit.withinCutoff.map(brief),
    afterCutoff: result.audit.afterCutoff.map(brief),
    stale: result.audit.stale.map((entry) => ({ id: entry.id, registered: entry.n, actual: entry.actual })),
    registry: result.audit.registrySize,
    registryReadings: result.audit.registryReadings,
  }
}

/**
 * 一次完整检查（纯读盘；写盘路径只在 `writeRegistry` 里）。
 *
 * **存量登记只对"本仓载体"生效**（{@link isProjectCarrier}）：换了载体（夹具 / 别的台账）就按零登记判，
 * 免得探针跑一次把几百条存量全判成"过期"。`scope` 把这件事写进读数，读者不用猜。
 */
export function check(options = {}) {
  const requested = options.carrier ?? CARRIER
  const carrier = readCarrier(requested)
  const project = isProjectCarrier(requested)
  const registry = options.registry ?? (project ? KNOWN_UNMARKED : [])
  const asOf = options.asOf ?? (project ? REGISTRY_AS_OF : '')
  const scope = project ? 'project' : 'probe'
  if (carrier === undefined) {
    const scan = scanRecords([])
    return { carrier: undefined, scope, records: [], scan, audit: audit(scan, registry, asOf) }
  }
  const records = parseVerifications(carrier.text)
  const scan = scanRecords(records)
  return { carrier: carrier.path, scope, records, scan, audit: audit(scan, registry, asOf) }
}

/** 写盘前的**产物自证**（`DEF-179` 的同族纪律：坏产物宁可写前就炸）。 */
export function assertWritable(source, next, expected, asOf) {
  const once = (text, sentinel) => text.split(sentinel).length - 1
  for (const sentinel of [REGISTRY_BEGIN, REGISTRY_END]) {
    if (once(next, sentinel) !== 1) throw new Error(`产物里哨兵 ${sentinel} 必须恰好出现 1 次`)
  }
  const reparsed = readRegistry(next)
  if (reparsed.asOf !== asOf) throw new Error(`产物回读的 asOf（${reparsed.asOf}）≠ 现算（${asOf}）`)
  const same = (a, b) => a.length === b.length && a.every((entry, at) => entry.id === b[at].id && entry.n === b[at].n && entry.why === b[at].why)
  if (!same(reparsed.entries, expected)) throw new Error('产物回读的登记与现算不等：表体结构被改坏')
  if (!next.includes('export const KNOWN_UNMARKED')) throw new Error('产物丢了 KNOWN_UNMARKED 的读回点：生成物只许动哨兵之间的注释')
  if (once(source, REGISTRY_BEGIN) !== 1) throw new Error('原文缺哨兵，拒绝写盘')
}

/** 把登记表写回本文件（只动两个哨兵之间的表体）。 */
export function writeRegistry(entries, asOf, file) {
  const target = file ?? SELF
  const source = readFileSync(target, 'utf8')
  const begin = source.indexOf(REGISTRY_BEGIN)
  const end = source.indexOf(REGISTRY_END)
  if (begin === -1 || end === -1 || end < begin) throw new Error('本文件缺 known-unmarked 哨兵')
  const head = source.slice(0, begin + REGISTRY_BEGIN.length)
  const tail = source.slice(end)
  const next = `${head}\n${renderRegistry(entries, asOf)}\n${tail}`
  assertWritable(source, next, entries, asOf)
  writeFileSync(target, next, 'utf8')
  return { written: entries.length, asOf }
}

/** 登记表与现算的**差集**（重生成时逐条打印：静默重生成就是"把守卫关掉"）。 */
export function registryDelta(registry, entries) {
  const before = new Map(registry.map((entry) => [entry.id, entry]))
  const after = new Map(entries.map((entry) => [entry.id, entry]))
  const added = [...after.keys()].filter((id) => !before.has(id))
  const removed = [...before.keys()].filter((id) => !after.has(id))
  const changed = [...after.keys()]
    .filter((id) => before.has(id) && before.get(id).n !== after.get(id).n)
    .map((id) => `${id}: ${before.get(id).n} → ${after.get(id).n}`)
  return { added, removed, changed }
}

